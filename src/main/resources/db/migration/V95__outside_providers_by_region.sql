-- sites, Kenya Times profiles and transport directories, Nov 2026; those disagree in places, so staff should confirm. Prices stay
-- estimates (fare_confirmed false). Nationwide Courier is a courier, not a route, and keeps its towns. Kukena and Guardian Angel have no
-- sourced towns yet, so customers type their place and staff quote it. Anything staff priced themselves is left alone.
UPDATE transport_stop s SET hidden = TRUE
FROM transport_operator o
WHERE o.id = s.operator_id AND o.kind = 'OUTSIDE' AND NOT s.fare_confirmed AND o.name <> 'Nationwide Courier';

