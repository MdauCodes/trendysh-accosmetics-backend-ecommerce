WHERE operator_id = (SELECT id FROM transport_operator WHERE name = 'Rider (boda boda)')
  AND name IN ('Machakos', 'Kajiado', 'Isinya', 'Namanga', 'Tala', 'Kangundo', 'Matuu', 'Matuu Road', 'Makuyu', 'Kenol',
               'Sagana', 'Murang''a', 'Naivasha', 'Naivasha Road', 'Gilgil', 'Karatina', 'Kerugoya', 'Nakuru', 'Nyeri', 'Embu');

